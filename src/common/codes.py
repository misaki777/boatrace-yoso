def wind_class(direction: int | None) -> str | None:
    """風向番号を 追い風/向かい風/無風/横風 に分類する。欠損は None。"""
    if direction is None:
        return None
    if direction == 17:
        return WIND_NONE
    if 3 <= direction <= 7:
        return WIND_TAIL
    if 11 <= direction <= 15:
        return WIND_HEAD
    if 1 <= direction <= 16:
        return WIND_CROSS
    raise ValueError(f"未知の風向番号です: {direction}")


