def make_race_id(ymd: str, stadium_number: int, race_number: int) -> str:
    """race_id を作る。ymd は 'YYYYMMDD' または 'YYYY-MM-DD'。例: 20261102-02-01"""
    digits = ymd.replace("-", "")
    if len(digits) != 8 or not digits.isdigit():
        raise ValueError(f"日付の形式が不正です: {ymd}")
    if not 1 <= stadium_number <= 24:
        raise ValueError(f"場番号が範囲外です: {stadium_number}")
    if not 1 <= race_number <= 12:
        raise ValueError(f"R番号が範囲外です: {race_number}")
    return f"{digits}-{stadium_number:02d}-{race_number:02d}"


def parse_race_id(race_id: str) -> tuple[str, int, int]:
    """race_id を (YYYYMMDD, 場番号, R番号) に分解する。"""
    parts = race_id.split("-")
    if len(parts) != 3:
        raise ValueError(f"race_id の形式が不正です: {race_id}")
    ymd, stadium, race = parts
    return ymd, int(stadium), int(race)
