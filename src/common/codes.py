def is_finish(place: int | None) -> bool:
    """着順が付いた(1〜6着)か。"""
    return place is not None and 1 <= place <= 6


def finish_position(place: int | None) -> int | None:
    """着順(1〜6)。着順が付かなかった場合は None。"""
    return place if is_finish(place) else None


def is_disqualified(place: int | None) -> bool:
    """出走したが失格になったか(7〜13)。"""
    return place is not None and 7 <= place <= 13


def is_absent(place: int | None) -> bool:
    """出走しなかったか(F・L欠場、欠場: 14〜16)。"""
    return place is not None and 14 <= place <= 16


